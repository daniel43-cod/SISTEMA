using API_SISTEMA.Data;
using API_SISTEMA.Models;
using Microsoft.EntityFrameworkCore;

// Solo genera SQL: no abre conexiones ni modifica bases de datos.
using var db = new CatalogoDb();
var sql = db.Database.GenerateCreateScript();
var passed = 0;
void Check(bool condition, string message)
{
    if (!condition) throw new Exception(message);
    passed++; Console.WriteLine("OK " + message);
}
foreach (var tabla in new[] { "zona_entrega", "pedido_catalogo", "detalle_pedido_catalogo" })
    Check(sql.Contains("CREATE TABLE public." + tabla), "Tabla PostgreSQL: " + tabla);
Check(sql.Split("GENERATED BY DEFAULT AS IDENTITY").Length - 1 >= 3, "Identificadores autogenerados");
Check(sql.Contains("timestamp(3) with time zone") && sql.Contains("DEFAULT (CURRENT_TIMESTAMP)"), "Fecha UTC con precisión de milisegundos");
Check(sql.Contains("estado smallint"), "Estado numérico compatible con PostgreSQL");
Check(sql.Contains("length(btrim(nombre_cliente))") && sql.Contains("length(btrim(nombre_producto))"), "Se conservan validaciones de textos");
Check(sql.Contains("GENERATED ALWAYS AS (CAST(cantidad * precio_unitario AS numeric(18,2))) STORED"), "Subtotal calculado y almacenado");
foreach (var relacion in new[] { "FK_pedido_catalogo_zona", "FK_pedido_catalogo_venta", "FK_detalle_pedido_catalogo_pedido", "FK_detalle_pedido_catalogo_presentacion" })
    Check(sql.Contains(relacion), "Relación conservada: " + relacion);
Check(sql.Contains("UQ_pedido_catalogo_operacion") && sql.Contains("UQ_detalle_pedido_catalogo_presentacion"), "Claves únicas de operación y presentación");
Check(sql.Contains("WHERE id_venta IS NOT NULL"), "Índice parcial de venta vinculada");
Check(sql.Contains("WHERE id_venta IS NOT NULL") && sql.Contains("CURRENT_TIMESTAMP"), "SQL PostgreSQL para filtros y fechas");
foreach (var tabla in new[] { "productos", "presentaciones", "producto_presentacion" })
    Check(sql.Contains("CREATE TABLE " + tabla + " ("), "Tabla PostgreSQL de productos: " + tabla);
Check(!sql.Contains("\"producto_presentacion \""), "Nombre de tabla sin espacio final");
Check(sql.Contains("stock_minimo >= 0") && sql.Contains("unidades_equivalentes > 0"), "Restricciones de mínimo y unidades conservadas");
Check(sql.Contains("precio_promedio_compra numeric(18,6)") && sql.Contains("precio numeric(18,2)"), "Precisión de costo promedio y precio");
Check(sql.Contains("fecha_creacion timestamp without time zone"), "Fecha de producto conserva hora local de Guatemala");
Check(sql.Contains("REFERENCES marca") && sql.Contains("REFERENCES productos") && sql.Contains("REFERENCES presentaciones") && sql.Contains("REFERENCES producto_presentacion"), "Relaciones de producto, marca, presentación y pedido");
Check(sql.Contains("codigo_barra character varying(100)") && sql.Contains("imagen character varying(2048)"), "Límites coherentes con los formularios existentes");
Console.WriteLine($"{passed} comprobaciones aprobadas; sin conexión a base de datos.");

sealed class CatalogoDb : DbContext
{
    protected override void OnConfiguring(DbContextOptionsBuilder options) =>
        options.UseNpgsql("Host=localhost;Database=solo_generacion_sql");
    protected override void OnModelCreating(ModelBuilder b)
    {
        // Las dependencias se representan solo con su PK; se adaptarán en su propio módulo.
        foreach (var property in typeof(Ventas).GetProperties().Where(p => p.Name != nameof(Ventas.id_ventas)))
            b.Entity<Ventas>().Ignore(property.Name);
        b.Entity<Ventas>().ToTable("ventas").HasKey(v => v.id_ventas);
        foreach (var property in typeof(Marca).GetProperties().Where(p => p.Name != nameof(Marca.IdMarca)))
            b.Entity<Marca>().Ignore(property.Name);
        b.Entity<Marca>().ToTable("marca").HasKey(m => m.IdMarca);
        b.Entity<Productos>().Ignore(p => p.DetalleVentas).Ignore(p => p.ProductoPrecios);
        b.ApplyConfiguration(new ProductoConfiguration());
        b.ApplyConfiguration(new PresentacionConfiguration());
        b.ApplyConfiguration(new ProductoPresentacionConfiguration());
        b.ApplyConfiguration(new ZonaEntregaConfiguration());
        b.ApplyConfiguration(new PedidoCatalogoConfiguration());
        b.ApplyConfiguration(new DetallePedidoCatalogoConfiguration());
    }
}